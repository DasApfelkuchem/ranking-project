/**
 * HTTP API server for rider rankings.
 * This server provides endpoints to query rider ranks and points.
 * 
 * Run with: node get-rider-rank-api.js
 * 
 * API Endpoints:
 *   GET /api/rider?name=Jelle%20Dillen&year=2026&gender=male&discipline=flatland
 *   Returns: { rank, points, name, year, gender, discipline }
 *            or { error: "Rider not found" }
 * 
 * The server loads rankings from localStorage export files or in-memory data
 * passed via POST /api/rankings
 */

const http = require('http');
const url = require('url');
const fs = require('fs');
const path = require('path');

const PORT = process.env.PORT || 6789;

// In-memory rankings cache: "flatland-male-2026" -> [{rank, name, points}, ...]
let rankingsData = new Map();

/**
 * Normalize a rider name for case-insensitive comparison
 */
function normalizeName(name) {
  if (!name) return '';
  return String(name)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // Remove diacritics
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Load rankings from JSON file (generated by export-rankings.js)
 */
function loadRankingsFromFile(discipline, gender, year) {
  const cacheKey = `${discipline}-${gender}-${year}`;
  
  if (rankingsData.has(cacheKey)) {
    return rankingsData.get(cacheKey);
  }
  
  try {
    const filePath = path.join(__dirname, 'docs', 'api', 'rankings', `rankings-${gender}.json`);
    
    if (!fs.existsSync(filePath)) {
      console.log(`File not found: ${filePath}`);
      return null;
    }
    
    const content = fs.readFileSync(filePath, 'utf8');
    const rankings = JSON.parse(content);
    
    // Cache it
    rankingsData.set(cacheKey, rankings);
    return rankings;
  } catch (err) {
    console.error(`Error loading rankings from ${discipline}/${gender}:`, err.message);
    return null;
  }
}

/**
 * Find a rider by name in the rankings
 */
function findRider(name, discipline, gender, year) {
  const rankings = loadRankingsFromFile(discipline, gender, year);
  
  if (!rankings || !Array.isArray(rankings)) {
    return { error: `No rankings found for ${discipline} ${gender}` };
  }
  
  const normalizedSearch = normalizeName(name);
  
  for (const entry of rankings) {
    const entryName = entry.name || entry.rider;
    if (normalizeName(entryName) === normalizedSearch) {
      return {
        rank: entry.rank,
        points: entry.points,
        name: entryName,
        discipline,
        gender,
        year
      };
    }
  }
  
  return { error: `Rider "${name}" not found in ${discipline} ${gender} rankings` };
}

/**
 * Handle CORS pre-flight requests
 */
function handleOptions(res) {
  res.writeHead(200, {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type'
  });
  res.end();
}

/**
 * Handle ranking data POST (for browser to send calculated rankings)
 */
function handlePostRankings(req, res) {
  let body = '';
  
  req.on('data', chunk => {
    body += chunk.toString();
  });
  
  req.on('end', () => {
    try {
      // Body format: JSON object with gender -> [{rank, name, points}, ...]
      const data = JSON.parse(body);
      
      if (typeof data === 'object' && data !== null) {
        // Store each gender's rankings
        for (const [gender, rankings] of Object.entries(data)) {
          if (Array.isArray(rankings)) {
            const cacheKey = `browser-${gender}-current`;
            rankingsData.set(cacheKey, rankings);
            console.log(`Loaded ${rankings.length} ${gender} riders from browser export`);
          }
        }
        
        res.writeHead(200, {
          'Content-Type': 'application/json',
          'Access-Control-Allow-Origin': '*'
        });
        res.end(JSON.stringify({ success: true, message: 'Rankings updated' }));
      } else {
        throw new Error('Invalid data format');
      }
    } catch (err) {
      console.error('Error processing rankings POST:', err.message);
      res.writeHead(400, {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*'
      });
      res.end(JSON.stringify({ error: err.message }));
    }
  });
}

/**
 * Handle POST request to save riders_all.txt (from browser)
 */
function handleSaveRidersAll(req, res) {
  let body = '';
  
  req.on('data', chunk => {
    body += chunk.toString();
  });
  
  req.on('end', () => {
    try {
      const filePath = path.join(__dirname, 'riders_all.txt');
      fs.writeFileSync(filePath, body, 'utf8');
      
      res.writeHead(200, {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*'
      });
      res.end(JSON.stringify({ success: true, message: 'File saved' }));
    } catch (err) {
      console.error('Error saving riders_all.txt:', err.message);
      res.writeHead(500, {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*'
      });
      res.end(JSON.stringify({ error: err.message }));
    }
  });
}

/**
 * Handle GET request for rider rank
 */
function handleGetRider(queryParams, res) {
  const name = queryParams.name;
  const year = queryParams.year || '2026';
  const gender = queryParams.gender || 'male';
  const discipline = queryParams.discipline || 'flatland';
  
  if (!name) {
    res.writeHead(400, {
      'Content-Type': 'application/json',
      'Access-Control-Allow-Origin': '*'
    });
    res.end(JSON.stringify({ error: 'Missing required parameter: name' }));
    return;
  }
  
  const result = findRider(name, discipline, gender, year);
  
  res.writeHead(result.error ? 404 : 200, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*'
  });
  res.end(JSON.stringify(result));
}

/**
 * HTTP server
 */
const server = http.createServer((req, res) => {
  const parsedUrl = url.parse(req.url, true);
  const pathname = parsedUrl.pathname;
  const query = parsedUrl.query;
  
  // OPTIONS for CORS
  if (req.method === 'OPTIONS') {
    handleOptions(res);
    return;
  }
  
  // POST endpoints
  if (req.method === 'POST') {
    if (pathname === '/api/rankings') {
      handlePostRankings(req, res);
      return;
    }
    if (pathname === '/save-riders_all') {
      handleSaveRidersAll(req, res);
      return;
    }
  }
  
  // GET endpoints
  if (req.method === 'GET') {
    if (pathname === '/api/rider') {
      handleGetRider(query, res);
      return;
    }
    
    // Health check
    if (pathname === '/health' || pathname === '/') {
      res.writeHead(200, {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*'
      });
      res.end(JSON.stringify({ 
        status: 'ok',
        endpoints: [
          'GET /api/rider?name=...&year=2026&gender=male&discipline=flatland',
          'POST /api/rankings - Upload rankings data from browser',
          'GET /health - Health check'
        ]
      }));
      return;
    }
  }
  
  // 404
  res.writeHead(404, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*'
  });
  res.end(JSON.stringify({ error: 'Endpoint not found' }));
});

server.listen(PORT, () => {
  console.log(`\n${'='.repeat(70)}`);
  console.log(`Rider Ranking API Server`);
  console.log(`${'='.repeat(70)}`);
  console.log(`Server running on http://localhost:${PORT}`);
  console.log(`\nAPI Endpoints:`);
  console.log(`  GET  /api/rider?name=Jelle%20Dillen&year=2026&gender=male`);
  console.log(`  POST /api/rankings - Upload rankings data`);
  console.log(`  POST /save-riders_all - Save riders_all.txt`);
  console.log(`  GET  /health - Health check`);
  console.log(`${'='.repeat(70)}\n`);
});

server.on('error', (err) => {
  console.error('Server error:', err.message);
  process.exit(1);
});

process.on('SIGTERM', () => {
  console.log('\nServer shutting down...');
  server.close();
  process.exit(0);
});
